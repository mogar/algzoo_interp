"""Tabulate causal_tests.py results across models into results/compare/causal.md.

Reads results/<model>/causal/summary.json for each model directory given
(default: the five 32x10 seeds). Flip rates are averaged over steps 2..T-2,
leaving out the last step where the readout reads every neuron directly.

Example:
    python scripts/summarize_causal.py
"""

import argparse
import json
from pathlib import Path

import numpy as np

RESULTS_DIR = Path(__file__).resolve().parent.parent / "results"
DEFAULT = ["2nd_argmax_32x10", "2nd_argmax_32x10_seed1", "2nd_argmax_32x10_seed2",
           "2nd_argmax_32x10_seed3", "2nd_argmax_32x10_seed4"]


def mean_early(rates):
    return float(np.mean(rates[:-1]))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("models", nargs="*", default=DEFAULT)
    args = parser.parse_args()

    lines = [
        "# Causal tests across models",
        "",
        "Generated by `python scripts/summarize_causal.py` from each model's `causal/summary.json` "
        "(`python scripts/causal_tests.py ...` with that model's neuron numbers). Flip rates are means over "
        "patched steps 2..T-2. *Detector* is the new-max detector; *top-2* the new-top-2 detector; *below-2nd* "
        "the `relu(2nd0_prev - x_t)` neuron; *memory* the running-max neuron.",
        "",
        "| model | detector / top-2 / memory | add new max: detector alone / all but detector | "
        "add top-2: top-2 alone | reset edges cut: accuracy | veto cut: acc when max is last | "
        "below-2nd veto cut: acc (errors predicting last) | memory alone / all but memory |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name in args.models:
        s = json.load(open(RESULTS_DIR / name / "causal" / "summary.json"))
        add_max = list(s["flip_rates"]["add_max"].items())
        add_top2 = list(s["flip_rates"]["add_top2"].items())
        det, top2 = add_max[0][0].strip("{}"), add_max[1][0].strip("{}")
        resets = s["resets"]
        r_det, r_top2 = resets[det], resets[top2]
        veto = list(s["veto"].items())
        base = veto[0][1]
        det_cut, below_cut = veto[1][1], veto[2][1]
        mem = list(s["memory"].items())
        mem_name = mem[0][0].replace("memory ", "").strip("[]")
        lines.append(
            f"| {name.replace('2nd_argmax_', '')} | {det} / {top2} / {mem_name} "
            f"| {mean_early(add_max[0][1]):.2f} / {mean_early(add_max[3][1]):.2f} "
            f"| {mean_early(add_top2[1][1]):.2f} "
            f"| {r_det['accuracy']:.3f} → {r_det['accuracy_edges_cut']:.3f} (detector), "
            f"→ {r_top2['accuracy_edges_cut']:.3f} (top-2) "
            f"| {base['accuracy_by_argmax_pos'][-1]:.2f} → {det_cut['accuracy_by_argmax_pos'][-1]:.2f} "
            f"| {below_cut['accuracy']:.3f} ({below_cut['frac_errors_predicting_last']:.0%}) "
            f"| {np.mean(mem[0][1]['detector_t+1']):.2f} / {np.mean(mem[2][1]['detector_t+1']):.2f} |"
        )
    out = RESULTS_DIR / "compare" / "causal.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[6:]))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
