"""Exact accuracy (from exact cone enumeration) vs a sampled estimate, for seq_len-3 models.

Writes results/compare/exact_accuracy.md.

Example:
    python scripts/exact_accuracy.py --hidden 3 4 5 8
"""

import argparse
from pathlib import Path

import torch as th
from alg_zoo.tasks import task_2nd_argmax

from algzoo_interp import load_2nd_argmax, randn_inputs
from algzoo_interp.cones import enumerate_cones, exact_accuracy

RESULTS_DIR = Path(__file__).resolve().parent.parent / "results"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--hidden", type=int, nargs="+", default=[3, 4, 5, 8])
    parser.add_argument("--n", type=int, default=2**20)
    args = parser.parse_args()
    lines = ["# Exact vs sampled accuracy (seq_len 3)", "",
             f"Generated by `python scripts/exact_accuracy.py --hidden {' '.join(map(str, args.hidden))}`; "
             f"sampled on {args.n:,} float64 randn inputs.", "",
             "| model | cones | exact accuracy | sampled | sampled stderr | difference / stderr |", "|---|---|---|---|---|---|"]
    for h in args.hidden:
        model = load_2nd_argmax(h, 3).double()
        cones = enumerate_cones(model)
        exact = exact_accuracy(cones)
        x = randn_inputs(args.n, 3, dtype=th.float64)
        with th.no_grad():
            sampled = (model(x).argmax(-1) == task_2nd_argmax(x)).double().mean().item()
        se = (sampled * (1 - sampled) / args.n) ** 0.5
        lines.append(f"| {h}x3 | {len(cones)} | {exact:.5f} | {sampled:.5f} | {se:.5f} | {(exact - sampled) / se:+.2f} |")
    out = RESULTS_DIR / "compare" / "exact_accuracy.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[4:]))


if __name__ == "__main__":
    main()
