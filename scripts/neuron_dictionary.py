"""Build a neuron dictionary for one model: what each neuron tracks, and how much it matters.

For each neuron: best-matching boolean event (on/off agreement), best single
running value (affine R^2), best greedy multi-feature fit, fraction of inputs
active, and accuracy drop under mean ablation at all steps. Fits are pooled
over steps 1..seq_len-1 (step 0 is trivial), so a high score means the same
role at every step. Feature definitions are in algzoo_interp/features.py.

Writes results/<model>/dictionary/{dictionary.md, dictionary.json, r2.png}.

Examples:
    python scripts/neuron_dictionary.py --handcrafted 10
    python scripts/neuron_dictionary.py --hidden 32 --seq-len 10
    python scripts/neuron_dictionary.py --hidden 32 --seq-len 10 --seed 3
"""

import argparse
import json
import sys
from dataclasses import asdict
from pathlib import Path

import matplotlib.pyplot as plt
import torch as th
from alg_zoo.tasks import task_2nd_argmax

from alg_zoo import handcrafted_2nd_argmax

from algzoo_interp import ablate, randn_inputs, run_with_cache
from algzoo_interp.dictionary import ValueFitter, build_dictionary
from algzoo_interp.features import running_values
from algzoo_interp.loading import add_model_args, load_from_args
from algzoo_interp.plots import heatmap, savefig

RESULTS_DIR = Path(__file__).resolve().parent.parent / "results"


def ablation_drops(model, x):
    target = task_2nd_argmax(x)
    with th.no_grad():
        base = (run_with_cache(model, x).logits.argmax(-1) == target).float().mean().item()
        return [
            base - (ablate(model, x, neurons=[n], mode="mean").logits.argmax(-1) == target).float().mean().item()
            for n in range(model.hidden_size)
        ]


def write_markdown(entries, name, args, path):
    lines = [
        f"# Neuron dictionary: {name}",
        "",
        f"Generated by `python scripts/neuron_dictionary.py {args.cli}` on {args.n:,} randn inputs, "
        "fits pooled over steps 1..T-1. *Agree* is on/off agreement with the event; "
        "*R²* is the affine fit `h ≈ slope * feature + intercept`; *multi* is a greedy fit on up to "
        f"{args.multi_k} features. *All* is a linear fit on every candidate feature at once; *HC* is a linear "
        "fit on the handcrafted 10-step model's 22 hidden states (seq_len 10 only). *Drop* is the accuracy "
        "lost when the neuron is mean-ablated at all steps.",
        "",
        "| neuron | P(on) | best event (agree) | best value (R², slope, intercept) | multi (R²) | all R² | HC R² | drop | label |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for e in entries:
        hc = e.extra.get("r2_handcrafted_basis")
        lines.append(
            f"| {e.neuron} | {e.p_active:.2f} | `{e.best_event}` ({e.event_agreement:.3f}) "
            f"| `{e.best_value}` ({e.value_r2:.3f}, {e.value_slope:.2f}, {e.value_intercept:.2f}) "
            f"| {', '.join(f'`{f}`' for f in e.multi_features)} ({e.multi_r2:.3f}) "
            f"| {e.extra['r2_all_features']:.3f} | {'' if hc is None else f'{hc:.3f}'} "
            f"| {e.extra['ablation_drop']:.3f} | {e.label} |"
        )
    path.write_text("\n".join(lines) + "\n")
    print(f"  wrote {path}")


def plot_r2(r2, names, entries, path):
    # Show only features that are some neuron's best single fit, plus the
    # strongest overall, so the figure stays readable
    keep = sorted({names.index(e.best_value) for e in entries}
                  | set(r2.amax(1).argsort(descending=True)[:12].tolist()))
    hidden = r2.shape[1]
    fig, ax = plt.subplots(figsize=(2.5 + 0.3 * hidden, 1.5 + 0.28 * len(keep)))
    heatmap(ax, r2[keep], title="Single-feature R² (pooled over steps 1..T-1)",
            xlabel="neuron", yticks=[names[k] for k in keep], vmin=0, vmax=1)
    savefig(fig, path)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_model_args(parser)
    parser.add_argument("--n", type=int, default=2**16, help="randn inputs")
    parser.add_argument("--n-ablation", type=int, default=2**15, help="inputs for ablations")
    parser.add_argument("--multi-k", type=int, default=3, help="max features in the greedy fit")
    args = parser.parse_args()
    args.cli = " ".join(sys.argv[1:])

    model, name = load_from_args(args)
    model = model.eval()
    out = RESULTS_DIR / name / "dictionary"
    out.mkdir(parents=True, exist_ok=True)
    print(f"Neuron dictionary for {name} -> {out}")

    x = randn_inputs(args.n, model.seq_len)
    with th.no_grad():
        cache = run_with_cache(model, x)
    entries, names, r2 = build_dictionary(cache, multi_k=args.multi_k)
    for e, drop in zip(entries, ablation_drops(model, x[: args.n_ablation])):
        e.extra["ablation_drop"] = drop

    # Ceilings: linear fits on every candidate feature at once, and on the
    # handcrafted 10-step model's hidden states (its neurons as a basis)
    steps = list(range(1, model.seq_len))
    fitter = ValueFitter(cache, running_values(x), steps)
    bases = {"all_features": fitter}
    if model.seq_len == 10:
        with th.no_grad():
            hc = run_with_cache(handcrafted_2nd_argmax(10), x)
        bases["handcrafted_basis"] = ValueFitter(cache, {f"hc{i}": hc.h[:, :, i] for i in range(22)}, steps)
    for e in entries:
        for key, f in bases.items():
            e.extra[f"r2_{key}"] = f.fit(e.neuron, list(range(len(f.names))))[1]

    write_markdown(entries, name, args, out / "dictionary.md")
    with open(out / "dictionary.json", "w") as f:
        json.dump({"model": name, "n_inputs": args.n, "neurons": [asdict(e) for e in entries]}, f, indent=2)
    plot_r2(r2, names, entries, out / "r2.png")

    for e in entries:
        print(f"  {e.neuron:2d}  on={e.p_active:.2f}  drop={e.extra['ablation_drop']:.3f}  {e.label:45s}"
              f"  best value {e.best_value} R²={e.value_r2:.3f}  multi R²={e.multi_r2:.3f}")


if __name__ == "__main__":
    main()
